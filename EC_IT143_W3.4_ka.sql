-- Q1: How many vendors have a superior credit rating in terms of vendors?
-- Author: Audra Elizabeth Klotz

SELECT COUNT(*) AS [Vendors with Superior Credit Rating]
FROM Purchasing.Vendor
WHERE CreditRating =
(SELECT MIN(CreditRating)
    FROM Purchasing.Vendor);


-- Q2: How many employees have the job title Design Engineer?
-- Author: Emmanuel Adebisi Jatto

SELECT COUNT(*) as [Number of Design Engineers] 
FROM humanresources.employee
WHERE JobTitle = 
	'Design Engineer';


-- Q3: I want to know which sales territory generated the highest total sales in 2013. 
-- Please show the territory name and the total order amount.
-- Author: Festus Atanonsen

SELECT TOP 1
       SalesTerritory.Name,
       SUM(SalesOrderHeader.TotalDue) AS 'TotalOrder'
FROM Sales.SalesTerritory
INNER JOIN Sales.SalesOrderHeader
    ON SalesOrderHeader.TerritoryID = SalesTerritory.TerritoryID
WHERE YEAR(OrderDate) = 2013
GROUP BY SalesTerritory.Name
ORDER BY TotalOrder DESC;


-- Q4: Can you provide the first and last names along with the email addresses 
-- for all employees who have a job title containing the word 'Manager'?
-- Author: Eddy Mukuna

SELECT Person.FirstName,
       Person.LastName,
       EmailAddress.EmailAddress,
       Employee.JobTitle
FROM Person.Person
INNER JOIN Person.EmailAddress
    ON Person.BusinessEntityID = EmailAddress.BusinessEntityID
INNER JOIN HumanResources.Employee
    ON Employee.BusinessEntityID = Person.BusinessEntityID
WHERE JobTitle LIKE '%Manager%'
ORDER BY JobTitle;


-- Q5: Our executive team is evaluating bicycle sales performance across product categories. 
  -- We need to identify which product category generated the highest total sales revenue during 2013. 
  -- Additionally, report the total quantity sold and the number of sales orders contributing to that amount.
-- Author: Me

SELECT TOP 1
       ProductCategory.Name,
       SUM(SalesOrderDetail.LineTotal) AS TotalRevenue,
       SUM(SalesOrderDetail.OrderQty) AS TotalQuantitySold,
       COUNT(DISTINCT SalesOrderHeader.SalesOrderID) AS NumberOfOrders
FROM Sales.SalesOrderHeader
INNER JOIN Sales.SalesOrderDetail
    ON SalesOrderHeader.SalesOrderID = SalesOrderDetail.SalesOrderID
INNER JOIN Production.Product
    ON SalesOrderDetail.ProductID = Product.ProductID
INNER JOIN Production.ProductSubcategory
    ON Product.ProductSubcategoryID = ProductSubcategory.ProductSubcategoryID
INNER JOIN Production.ProductCategory
    ON ProductSubcategory.ProductCategoryID = ProductCategory.ProductCategoryID
WHERE YEAR(SalesOrderHeader.OrderDate) = 2013
GROUP BY ProductCategory.Name
ORDER BY TotalRevenue DESC;


-- Q6: Our warehouse team is worried about slow sellers. Some products have never appeared on a sales order. 
-- Please list those unsold products with their name and list price, highest price first, so we can decide what to discontinue.
-- Author: Nathaniel Neyor, II

SELECT Product.Name,
       Product.ListPrice
FROM Production.Product
LEFT JOIN Sales.SalesOrderDetail
    ON SalesOrderDetail.ProductID = Product.ProductID
WHERE OrderQty is null
ORDER BY ListPrice DESC;


-- Q7: Which AdventureWorks tables contain a column named ProductID, and what is the data type of that column?
-- Author: Me

SELECT TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME, DATA_TYPE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE COLUMN_NAME = 'productid'
ORDER BY TABLE_SCHEMA, TABLE_NAME;


-- Q8: How many base tables are defined in the Sales schema of the AdventureWorks database? 
-- Author: Karen Janeth Caballero Valderrama

SELECT COUNT(*) AS [No. of Base Tables]
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_TYPE = 'BASE TABLE'
  AND TABLE_SCHEMA = 'Sales';